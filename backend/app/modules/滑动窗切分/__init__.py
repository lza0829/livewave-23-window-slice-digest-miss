"""滑动窗切分（已实现）

全局唯一窗格引擎，主链入流归属、关窗、贯验都以此为准：

- 窗起一律按「滑动步长」对齐（epoch 取模），窗长固定，窗 [起, 起+窗长)。
- 翻滚 = 步长等于窗长的退化滑动：窗互不重叠，每事件恰落 1 窗。
- 滑动 = 步长小于窗长：相邻窗重叠覆盖，每事件恰落 窗长/步长 扇窗。
- 归属口径（固定）：多窗归属——事件计入所有覆盖它的窗，整集原子，
  不得半截入窗；主窗 = 窗起最大（最新）那扇，仅作展示与单键字段。
- 禁止用翻滚对齐冒充滑动：对齐模数是步长，不是窗长。
"""
from app.services import 时间

状态 = "已实现"

窗型集 = ("翻滚", "滑动")


落窗上限 = 120


def 校验窗参(窗型: str, 窗长秒: int, 滑动步长秒: int) -> list:
    """窗参合法性；返回问题列表，空表 = valid。"""
    问题 = []
    if 窗型 not in 窗型集:
        问题.append(f"窗型非法:{窗型}（须为 {'/'.join(窗型集)}）")
    if not isinstance(窗长秒, int) or 窗长秒 <= 0:
        问题.append(f"窗长秒须为正整数:{窗长秒}")
        return 问题
    if not isinstance(滑动步长秒, int) or 滑动步长秒 <= 0:
        问题.append(f"滑动步长秒须为正整数:{滑动步长秒}")
        return 问题
    if 窗型 == "翻滚" and 滑动步长秒 != 窗长秒:
        问题.append(f"翻滚窗步长须等于窗长（步长{滑动步长秒}≠窗长{窗长秒}）")
    if 窗型 == "滑动":
        if 滑动步长秒 > 窗长秒:
            问题.append(f"滑动步长不得大于窗长（步长{滑动步长秒}>窗长{窗长秒}，会漏窗）")
        elif 窗长秒 % 滑动步长秒 != 0:
            问题.append(f"窗长须为步长整数倍（{窗长秒}%{滑动步长秒}≠0，落窗数会漂移）")
        elif 窗长秒 // 滑动步长秒 > 落窗上限:
            问题.append(f"单事件落窗{窗长秒 // 滑动步长秒}扇超上限{落窗上限}")
    return 问题


def 每事件窗数(窗长秒: int, 滑动步长秒: int) -> int:
    """每事件恰落窗数：翻滚=1，滑动=窗长/步长。"""
    return 窗长秒 // 滑动步长秒


def 对齐步起(事件时: str, 滑动步长秒: int) -> str:
    """不大于事件时的最大步长对齐窗起。"""
    return 时间.对齐窗起(事件时, 滑动步长秒)


def 事件窗起集(事件时: str, 窗长秒: int, 滑动步长秒: int) -> list:
    """覆盖事件时的全部窗起（升序，恰 窗长/步长 个）；末位即主窗窗起。"""
    k = 每事件窗数(窗长秒, 滑动步长秒)
    末起 = 对齐步起(事件时, 滑动步长秒)
    return [时间.加秒(末起, -i * 滑动步长秒) for i in range(k - 1, -1, -1)]
