"""改步长×入流并发演练：在真实库上复现并核查硬约束。

演练会推进水位并切换全局窗参（窗参史留痕）。步骤：
1. 备演练房 → 2. 排水清场 → 3. 切滑动60/30 → 4. 入流开新窗 →
5. 开着窗改步长（须失败闭）→ 6. 线程并发：入流×改步长（不得半截双套窗键）→
7. 排水 → 8. 换代改步长（须成功）→ 9. 新代入流 → 10. 贯验。
"""
import threading
import uuid

from fastapi import HTTPException

from app.db import 连接
from app.seed import 此刻
from app.services import 时间, 窗参, 装载, 贯验

演练房 = "房演"


def _备房() -> None:
    conn = 连接()
    try:
        if not conn.execute("SELECT 1 FROM 直播间 WHERE 房间键=?", (演练房,)).fetchone():
            conn.execute(
                "INSERT INTO 直播间(房间键, 标题, 主播, 开播事件时, 状态) VALUES (?,?,?,?,?)",
                (演练房, "改步长并发演练", "演练员", "2026-11-22T12:00:00Z", "直播中"),
            )
            conn.execute(
                "INSERT INTO 水位线(房间键, 事件时水位, 允许迟到秒, 更新处理时) VALUES (?,?,?,?)",
                (演练房, "2026-11-22T12:00:00Z", 30, 此刻()),
            )
        conn.commit()
    finally:
        conn.close()


def _水位(房间键: str) -> str:
    conn = 连接()
    try:
        return conn.execute("SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()["事件时水位"]
    finally:
        conn.close()


def _窗参() -> dict:
    conn = 连接()
    try:
        return 窗参.当前窗参(conn)
    finally:
        conn.close()


def _事件(编号: str, 事件时: str, 赞: int) -> dict:
    return {
        "事件编号": 编号, "房间键": 演练房, "事件类型": "点赞",
        "事件时": 事件时, "处理时": 事件时, "观众键": "演练", "点赞增量": 赞, "送礼额": 0,
    }


def _开启窗代数() -> list:
    conn = 连接()
    try:
        return [
            dict(r)
            for r in conn.execute(
                """SELECT 房间键, COUNT(DISTINCT 窗代) AS 代数
                   FROM 热度窗 WHERE 状态='开启' GROUP BY 房间键 HAVING 代数>1"""
            )
        ]
    finally:
        conn.close()


def _批次窗代集(批次编号: str) -> set:
    conn = 连接()
    try:
        return {
            r["窗代"]
            for r in conn.execute(
                "SELECT DISTINCT 窗代 FROM 互动事件 WHERE 批次编号=? AND 命运='已入窗'", (批次编号,)
            )
        }
    finally:
        conn.close()


def 改步长并发演练() -> dict:
    步骤 = []
    核查 = []

    def 记(名: str, 果) -> None:
        步骤.append({"步骤": 名, "结果": 果})

    def 核(项: str, 通过: bool, 注: str = "") -> None:
        核查.append({"项": 项, "通过": bool(通过), "注": 注})

    运行号 = uuid.uuid4().hex[:8]
    _备房()

    排1 = 窗参.排水()
    记("① 排水清场（全部开启窗关闭）", 排1)

    参0 = _窗参()
    if (参0["窗型"], 参0["窗长秒"], 参0["滑动步长秒"]) != ("滑动", 60, 30):
        切 = 窗参.改窗参("滑动", 60, 30)
        记("② 切窗参 滑动60/30", 切)
    else:
        记("② 已是 滑动60/30", {"窗代": 参0["窗代"]})
    代前 = _窗参()["窗代"]

    基 = _水位(演练房)
    批1 = f"演-{运行号}-1"
    报1 = 装载.装一批({
        "批次编号": 批1,
        "事件": [_事件(f"{批1}-a", 时间.加秒(基, 70), 3),
                 _事件(f"{批1}-b", 时间.加秒(基, 85), 2)],
    })
    记("③ 入流批1（开出滑动窗，保持开启）", {"入窗": 报1["入窗"], "窗代": 报1["窗代"]})

    try:
        窗参.改窗参("滑动", 60, 20)
        记("④ 开着窗改步长 60/20", "未拒绝（异常！）")
        核("开窗改步长失败闭", False, "改参未被拒绝")
    except HTTPException as e:
        记("④ 开着窗改步长 60/20", f"失败闭拒绝 ✓（{e.status_code}）")
        核("开窗改步长失败闭", e.status_code == 409, f"HTTP {e.status_code}")

    
    批2 = f"演-{运行号}-2"
    并发结果 = {}

    def 流入():
        并发结果["批2"] = 装载.装一批({
            "批次编号": 批2,
            "事件": [_事件(f"{批2}-a", 时间.加秒(基, 100), 1),
                     _事件(f"{批2}-b", 时间.加秒(基, 115), 4)],
        })

    def 改参():
        try:
            并发结果["改参"] = 窗参.改窗参("滑动", 60, 15)
        except HTTPException as e:
            并发结果["改参"] = {"失败闭": True, "状态码": e.status_code}

    t1, t2 = threading.Thread(target=流入), threading.Thread(target=改参)
    t1.start(); t2.start(); t1.join(); t2.join()
    批2代 = _批次窗代集(批2)
    双代 = _开启窗代数()
    记("⑤ 并发：入流批2 × 改步长60/15", {
        "批2入窗": 并发结果["批2"]["入窗"], "批2窗代": sorted(批2代),
        "改参": 并发结果["改参"], "双代开启房": 双代,
    })
    核("并发批2窗代单一", 批2代 == {代前}, f"批2窗代={sorted(批2代)}")
    核("并发改步长仍失败闭", 并发结果["改参"].get("状态码") == 409, str(并发结果["改参"]))
    核("无同房双代开启窗", not 双代, str(双代))

    排2 = 窗参.排水(房间键=演练房)
    记("⑥ 排水演练房", 排2)

    切2 = 窗参.改窗参("滑动", 60, 20)
    记("⑦ 排水后改步长 60/20（换代隔离）", 切2)
    核("排水后换代成功", 切2.get("已变更") is True, str(切2))

    批3 = f"演-{运行号}-3"
    报3 = 装载.装一批({
        "批次编号": 批3,
        "事件": [_事件(f"{批3}-a", 时间.加秒(基, 200), 5),
                 _事件(f"{批3}-b", 时间.加秒(基, 215), 1)],
    })
    批3代 = _批次窗代集(批3)
    记("⑧ 新代入流批3（每事件应落3窗）", {
        "入窗": 报3["入窗"], "窗代": 报3["窗代"], "每事件窗数": 报3["每事件窗数"],
    })
    核("批3全属新代", 批3代 == {切2["窗代"]}, f"批3窗代={sorted(批3代)}")
    核("批3每事件3窗(60/20)", 报3["每事件窗数"] == 3, str(报3["每事件窗数"]))

    验 = 贯验.跑贯验()
    记("⑨ 窗互证", {"是否通过": 验["是否通过"], "问题": 验["问题"]})
    核("贯验通过", 验["是否通过"], "；".join(验["问题"][:3]))

    结论 = "通过" if all(c["通过"] for c in 核查) else "失败"
    return {"结论": 结论, "步骤": 步骤, "核查": 核查,
            "说明": "演练推进了水位并切换全局窗参；窗参史留有各代记录"}
